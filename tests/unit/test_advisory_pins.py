"""What a requirements file yields to an advisory lookup, and what it must not swallow.

The accounting test is the one that matters. Every other case here could pass
while the parser quietly dropped a line it did not recognise, and a dropped line
is a package the audit never checks while reporting a clean file.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from mas_sentry.advisories.pins import Pin, PinSet, parse_pins, read_pins

ROOT = Path(__file__).resolve().parents[2]

# The shape pip-compile --generate-hashes writes: the pin on one line, its
# hashes on backslash continuations, and a "# via" block naming the dependents.
_LOCKFILE_EXCERPT = """\
#
# This file is autogenerated by pip-compile with Python 3.14
#
certifi==2026.10.23 \\
    --hash=sha256:a9895e6e2758b371e0545e321a3a8fd1fcfd9829ada8824a936dfb16aaaf36cd \\
    --hash=sha256:e9b54de76e530bb6cf0ccd036787103acb58fd42ba930ea8bf948ddbaa2f61d1
    # via
    #   httpcore
    #   httpx
h11==0.16.0 \\
    --hash=sha256:4e35b956cf45792e4caa5885e69fba00bdbc6ffafbfa020300e549b208ee5ff1
    # via httpcore
"""


def _names(result: PinSet) -> dict[str, str]:
    return {p.name: p.version for p in result.pins}


class TestLockfileShape:
    def test_a_pin_survives_its_hash_continuations(self) -> None:
        """The hashes sit on their own lines; read separately they are neither spec nor structure."""
        assert _names(parse_pins(_LOCKFILE_EXCERPT)) == {"certifi": "2026.10.23", "h11": "0.16.0"}

    def test_the_via_block_contributes_nothing(self) -> None:
        assert parse_pins(_LOCKFILE_EXCERPT).unpinned == ()

    def test_a_hash_on_the_requirement_line_does_not_break_it(self) -> None:
        """pip freeze and hand-written lockfiles both put the hash inline, where PEP 508 has no room."""
        result = parse_pins("certifi==2026.10.23 --hash=sha256:a9895e6e")
        assert _names(result) == {"certifi": "2026.10.23"}


class TestNames:
    @pytest.mark.parametrize("written", ["Flask-Cors", "flask_cors", "FLASK.CORS"])
    def test_a_name_is_canonical_however_the_publisher_spelled_it(self, written: str) -> None:
        """A feed is keyed on one spelling; matching on the file's spelling misses most packages."""
        assert _names(parse_pins(f"{written}==1.0")) == {"flask-cors": "1.0"}

    def test_extras_do_not_become_part_of_the_name(self) -> None:
        assert _names(parse_pins("httpx[http2]==0.28.1")) == {"httpx": "0.28.1"}

    def test_a_marker_does_not_hide_the_pin(self) -> None:
        """A pin that only installs on some interpreters is still a pin that installs."""
        assert _names(parse_pins('tomli==2.0.1 ; python_version < "3.11"')) == {"tomli": "2.0.1"}


class TestVersions:
    def test_an_exact_pin_is_kept_as_written(self) -> None:
        assert parse_pins("certifi==2026.10.23").pins[0].version == "2026.10.23"

    def test_arbitrary_equality_is_a_pin(self) -> None:
        """=== names one release even when the string is not a PEP 440 version."""
        assert _names(parse_pins("pkg===1.0-custom")) == {"pkg": "1.0-custom"}

    def test_an_extra_exclusion_does_not_unpin_an_exact_version(self) -> None:
        assert _names(parse_pins("pkg==1.0,!=1.0.1")) == {"pkg": "1.0"}

    def test_a_wildcard_pin_names_a_range_not_a_release(self) -> None:
        result = parse_pins("pkg==1.*")
        assert result.pins == ()
        assert "range" in result.unpinned[0].reason

    def test_two_conflicting_exact_pins_are_not_resolved_here(self) -> None:
        """Choosing one would invent a resolution the file does not state."""
        result = parse_pins("pkg==1.0,==2.0")
        assert result.pins == ()
        assert "more than one" in result.unpinned[0].reason


class TestWhatCannotBeLookedUp:
    def test_a_range_is_reported_not_dropped(self) -> None:
        result = parse_pins("httpx>=0.28")
        assert result.pins == ()
        assert len(result.unpinned) == 1

    def test_a_bare_name_is_reported(self) -> None:
        assert len(parse_pins("httpx").unpinned) == 1

    def test_a_direct_url_is_reported(self) -> None:
        result = parse_pins("pkg @ https://example.invalid/pkg-1.0.whl")
        assert "direct URL" in result.unpinned[0].reason

    def test_a_version_control_checkout_is_reported(self) -> None:
        result = parse_pins("git+https://example.invalid/pkg.git#egg=pkg")
        assert "revision" in result.unpinned[0].reason

    @pytest.mark.parametrize("line", ["-e .", "--editable ./src"])
    def test_an_editable_install_is_reported(self, line: str) -> None:
        result = parse_pins(line)
        assert "working tree" in result.unpinned[0].reason

    @pytest.mark.parametrize("line", ["-r base.txt", "--requirement base.txt", "-c constraints.txt"])
    def test_a_referenced_file_is_reported_rather_than_followed(self, line: str) -> None:
        """Its pins are not in this file, so silently skipping it answers for a set never read."""
        result = parse_pins(line)
        assert "did not follow" in result.unpinned[0].reason

    def test_an_unparseable_line_carries_the_parser_s_own_reason(self) -> None:
        result = parse_pins("pkg==1.0 junk")
        assert result.pins == ()
        assert result.unpinned[0].reason.startswith("not a PEP 508 requirement")

    def test_an_empty_version_is_not_a_pin(self) -> None:
        """ "pkg===" is a valid requirement with no version; admitting it would count an
        unexaminable package as covered."""
        result = parse_pins("pkg===")
        assert result.pins == ()
        assert "pins nothing" in result.unpinned[0].reason


class TestStructureIsNotARequirement:
    @pytest.mark.parametrize(
        "line",
        [
            "--index-url https://pypi.org/simple",
            "--extra-index-url https://example.invalid/simple",
            "--find-links /tmp/wheels",
            "--no-binary :all:",
            "# a comment",
            "",
            "   ",
        ],
    )
    def test_it_yields_nothing_either_way(self, line: str) -> None:
        assert len(parse_pins(line)) == 0


class TestAccounting:
    def test_every_requirement_line_lands_in_exactly_one_collection(self) -> None:
        """The R-2.1 case: a line the parser does not recognise must not simply vanish.

        Written as a count rather than as a lookup of each line, because the
        failure being guarded against is a line going missing, and a test that
        asked about lines by name could not notice one that did.
        """
        text = "\n".join(
            [
                "# header",
                "",
                "--index-url https://pypi.org/simple",
                "certifi==2026.10.23",
                "httpx>=0.28",
                "pkg @ https://example.invalid/pkg.whl",
                "git+https://example.invalid/other.git#egg=other",
                "-e .",
                "-r base.txt",
                "pkg===",
            ]
        )
        result = parse_pins(text)
        assert len(result.pins) == 1
        assert len(result.unpinned) == 6
        assert len(result) == 7

    def test_a_pin_keeps_the_line_it_came_from(self) -> None:
        """Evidence a reviewer can match against the file without rerunning the scan (R-7.2)."""
        pin = parse_pins("certifi==2026.10.23  # via httpx").pins[0]
        assert isinstance(pin, Pin)
        assert pin.raw == "certifi==2026.10.23"


class TestAgainstTheRepositorysOwnLockfile:
    """Read the real pip-compile artifact rather than only a fixture.

    A fixture reproduces the shapes its author thought of, which is how the
    hash-continuation case would have been missed. This file is regenerated by a
    tool nobody here controls, so it keeps the parser honest about what
    pip-compile actually writes.

    The assertions are about shape rather than about particular versions, which
    move whenever a pin is bumped.
    """

    def test_every_line_resolves_to_an_exact_pin(self) -> None:
        """Also an assertion about the lockfile: a hash-verified install has nothing unpinned."""
        result = read_pins(ROOT / "requirements-lock.txt")
        assert result.unpinned == ()
        assert len(result.pins) > 20

    def test_names_arrive_canonical_and_unique(self) -> None:
        """A duplicate after canonicalisation would mean two pins for one distribution."""
        pins = read_pins(ROOT / "requirements-lock.txt").pins
        names = [p.name for p in pins]
        assert names == [n.lower() for n in names]
        assert len(set(names)) == len(names)
